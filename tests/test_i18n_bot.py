def _weather():
    f = {"tmax": 18, "dry": True, "sun": True, "calm": True, "wet": True, "snow": False, "windy": True, "wind": 40, "tnight": -2}
    for wx in ({"dry": 1}, {"sun": 1, "calm": 1}, {"dry": 1, "calm": 1, "sun": 1}, {"tn": 0, "wet": 1, "windy": 1}, {"hot": 30}):
        yield nunu_wx.message({"wx": {**wx, "what": "Mango", "where": "Home"}}, f, date(2026, 5, 7), [], random.Random(1))[0]


def test_bot_messages_translated():
    # en хватает: ключи uk.json те же (test_i18n_web), а украинский перевод бывает равен русскому
    left = [s for s in SAMPLES + list(_weather()) if CYR.search(i18n.tr(s, "en").replace("Аня", "").replace("Петя", ""))]  # имена остаются
    assert not left, left[:5]
    assert i18n.tr("Петя заглянул", "ru") == "Петя заглянул"
    assert i18n.tr("👋 Петя заглянул к тебе на участок", "en") == "👋 Петя dropped by your plot"  # имя не трогаем
    assert i18n.tr("💬 Петя у «Ёлка»: привет", "uk") == "💬 Петя біля «Ёлка»: привет"  # написанное человеком — как есть
    assert i18n.lang_of({"nunu-prefs": {"lang": "uk"}}) == "uk" and i18n.lang_of({}) == "ru"
