admin = APIRouter(prefix="/nunu/admin/api/rules")
_run = {"on": False, "sent": 0, "fail": 0}


def _ok(data: str) -> bool:
    try:
        return ((json.loads(data).get("nunu-prefs") or {}).get("rules") or {}).get("v") == RULES_V
    except (ValueError, AttributeError):
        return False


def _pending(c) -> list[int]:
    out = []
    for r in c.execute("SELECT tg_id, data FROM state"):
        try:
            v = ((json.loads(r["data"]).get("nunu-prefs") or {}).get("rules") or {}).get("v")
        except (ValueError, AttributeError):
            v = None
        if v != RULES_V:
            out.append(r["tg_id"])
    sent = {r[0] for r in c.execute("SELECT uid FROM rules_sent WHERE v=?", (RULES_V,))}
    return [u for u in out if u not in sent]


def _db():
    c = nunu._db()
    c.execute("CREATE TABLE IF NOT EXISTS rules_sent (uid INTEGER NOT NULL, v INTEGER NOT NULL, PRIMARY KEY (uid, v))")
    return c


@admin.get("")
def stats(req: Request, x_admin_key: str | None = Header(default=None)):
    nunu_admin._auth(req, x_admin_key)
    with closing(_db()) as c:
        total = c.execute("SELECT COUNT(*) FROM state").fetchone()[0]
        left = len(_pending(c))
        ok = sum(_ok(r[0]) for r in c.execute("SELECT data FROM state"))
        sent = c.execute("SELECT COUNT(*) FROM rules_sent WHERE v=?", (RULES_V,)).fetchone()[0]
    return {"v": RULES_V, "total": total, "ok": ok, "todo": left, "sent": sent, "run": _run}


async def _broadcast(ids: list[int]) -> None:
    text = ("📜 В «Ну-ну» появился свод правил: как мы общаемся, что можно и нельзя, как работают жалобы "
            "и что видят друзья. Прочитай и прими их при следующем входе в игру — без этого игра не откроется.")
    try:
        for uid in ids:
            try:
                await nunu._notify(uid, text, nunu.link())
                _run["sent"] += 1
            except Exception as e:  # заблокировал бота и т. п.
                log.info("Правила %s: %s", uid, e)
                _run["fail"] += 1
            with closing(_db()) as c, c:
                c.execute("INSERT OR IGNORE INTO rules_sent(uid, v) VALUES(?, ?)", (uid, RULES_V))
            await asyncio.sleep(0.1)  # Telegram: не больше ~30 сообщений в секунду
    finally:
        _run["on"] = False


@admin.post("/broadcast")
async def broadcast(req: Request, x_admin_key: str | None = Header(default=None)):
    """Каждому, кто ещё не принял текущую версию, — одно сообщение (повторно не шлём)."""
    nunu_admin._auth(req, x_admin_key)
    if _run["on"]:
        return {"ok": False, "detail": "Рассылка уже идёт"}
    with closing(_db()) as c:
        ids = _pending(c)
    _run.update(on=True, sent=0, fail=0)
    nunu._bg(_broadcast(ids))
    return {"ok": True, "count": len(ids)}
